public class Card {
	private String suit;
	private String face;
	private int point;
	
	public String getSuit() {
		return suit;
	}
	
	public String getFace() {
		return face;
	}
	
	public String getPoint() {
		return point;
	}
	
	public void setSuit(String s) {
		suit = s;
	}
	
	public void setFace(String s) {
		face = s;
	}
	
	public void setPoint(int n) {
		point = n;
	}
}
